import type { ConsolaInstance } from "./_consola.ts";
import type { Hookable } from "./_hookable.ts";
import type { PresetName, PresetOptions } from "../presets/index.ts";
import type { FastnodeConfig, FastnodeOptions } from "./config.ts";
import type { FastnodeEventHandler } from "./handler.ts";
import type { FastnodeHooks } from "./hooks.ts";
import type { PrerenderRoute } from "./prerender.ts";
import type { Router } from "../core/routing/routing.ts";
import type { NormalizedRouteRules } from "./route-rules.ts";
import type { WorkerAddress } from "./runner.ts";

type MaybeArray<T> = T | T[];

/** Fastnode package metadata including version information. */
export interface FastnodeMeta {
  version: string;
  majorVersion: number;
}

/**
 * The core Fastnode instance available throughout the build lifecycle.
 *
 * Provides access to resolved options, hooks, the virtual file system,
 * scanned handlers, and utility methods.
 */
export interface Fastnode {
  meta: FastnodeMeta;
  options: FastnodeOptions;
  scannedHandlers: FastnodeEventHandler[];
  vfs: Map<string, { render: () => string | Promise<string> }>;
  hooks: Hookable<FastnodeHooks>;
  logger: ConsolaInstance;
  fetch: (input: Request) => Response | Promise<Response>;
  close: () => Promise<void>;
  updateConfig: (config: FastnodeDynamicConfig) => void | Promise<void>;
  routing: Readonly<{
    sync: () => void;
    routeRules: Router<NormalizedRouteRules & { _route: string }>;
    routes: Router<MaybeArray<FastnodeEventHandler & { _importHash: string }>>;
    globalMiddleware: (FastnodeEventHandler & { _importHash: string })[];
    routedMiddleware: Router<FastnodeEventHandler & { _importHash: string }>;
  }>;

  /** Routes generated by the last `prerender()` run. */
  _prerenderedRoutes?: PrerenderRoute[];
}

/**
 * Subset of {@link FastnodeConfig} that can be updated at runtime via
 * `fastnode.updateConfig()`.
 */
export type FastnodeDynamicConfig = Pick<FastnodeConfig, "runtimeConfig" | "routeRules">;

/**
 * Metadata about the framework using Fastnode.
 *
 * @see https://fastnode.khulnasoft.com/config/advanced#framework
 */
export interface FastnodeFrameworkInfo {
  name?: "fastnode" | (string & {});
  version?: string;
  /**
   * Command shown in build output as the suggested preview command.
   *
   * Display-only: Fastnode never executes this. Use this when the framework
   * wraps `fastnode preview` with its own CLI (e.g. `npx nuxt preview`).
   * Defaults to `npx fastnode preview`.
   */
  previewCommand?: string;
  /**
   * Command shown in build output as the suggested deploy command.
   *
   * Display-only: Fastnode never executes this. Use this when the framework
   * wraps `fastnode deploy` with its own CLI (e.g. `npx nuxt deploy`).
   * Defaults to `npx fastnode deploy --prebuilt`.
   */
  deployCommand?: string;
}

/**
 * Build info written to `<output.dir>/fastnode.json` (production, default
 * `.output/fastnode.json`) or `<rootDir>/node_modules/.fastnode/fastnode.dev.json`
 * (development).
 *
 * Contains preset, framework, version, and command information.
 */
export interface FastnodeBuildInfo {
  date: string;
  preset: PresetName;
  envName?: string;
  framework: FastnodeFrameworkInfo;
  versions: {
    fastnode: string;
    [key: string]: string;
  };
  commands?: {
    preview?: string;
    deploy?: string;
  };
  serverEntry?: string;
  publicDir?: string;
  dev?: {
    pid: number;
    workerAddress?: WorkerAddress;
    /** Public URL of the dev server (its first listener). */
    url?: string;
  };
  config?: Partial<PresetOptions>;
}
