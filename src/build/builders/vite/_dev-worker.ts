import type { Fastnode } from "fastnode/types";

import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { resolveModulePath } from "exsolve";
import { runtimeDir } from "#fastnode/meta";
import { resolve } from "pathe";
import { writeFile } from "../../../utils/fs.ts";
import { resolveViteModuleRunner, viteImportOptions } from "./_import.ts";

/**
 * Generate the entry the dev runner loads.
 *
 * The worker needs Vite's module runner, which Fastnode cannot import from its own `dist/`: `vite` is
 * an optional dependency resolved from the user project. The host resolves it and the generated
 * entry hands it over to the worker, so the module runner of the app's own `vite` is the one that
 * runs (same contract as the other runner dependencies, see `src/dev/runner-deps.ts`).
 */
export async function writeDevWorkerEntry(fastnode: Fastnode): Promise<string> {
  const entry = resolve(fastnode.options.buildDir, "vite/dev-worker.mjs");
  // Absolute `file://` URLs: the miniflare runner imports the entry by its path, so relative
  // specifiers cannot escape the entry directory in workerd (fails on windows).
  const devWorker = pathToFileURL(resolve(runtimeDir, "internal/vite/dev-worker.mjs")).href;
  const moduleRunner = pathToFileURL(
    await resolveViteModuleRunner(viteImportOptions(fastnode))
  ).href;
  const websocket = fastnode.options.features.websocket ?? fastnode.options.experimental.websocket;
  // Read on the host: the workerd runner does not see the host's environment variables.
  const reloadTimeout = _resolveReloadTimeout(fastnode);
  // The dev runner serves the worker with srvx: hand it the srvx tracing plugin, like the
  // production entries do (`tracingSrvxPlugins`), so `srvx.*` tracing channels are emitted in dev.
  const srvxTracing = fastnode.options.tracingChannel?.srvx
    ? pathToFileURL(resolveModulePath("srvx/tracing", { from: import.meta.url })).href
    : undefined;

  const lines = [
    "// Generated by Fastnode",
    `import * as moduleRunner from ${JSON.stringify(moduleRunner)};`,
    `import { setModuleRunner, setReloadWaitTimeout } from ${JSON.stringify(devWorker)};`,
    srvxTracing && `import { tracingPlugin as srvxTracing } from ${JSON.stringify(srvxTracing)};`,
    `export * from ${JSON.stringify(devWorker)};`,
    websocket && `export { websocketOptions as websocket } from ${JSON.stringify(devWorker)};`,
    srvxTracing && "export const plugins = [srvxTracing()];",
    "",
    "setModuleRunner(moduleRunner);",
    reloadTimeout && `setReloadWaitTimeout(${reloadTimeout});`,
  ];
  const contents = lines.filter((line) => typeof line === "string").join("\n") + "\n";

  const current = await readFile(entry, "utf8").catch(() => undefined);
  if (current !== contents) {
    await writeFile(entry, contents);
  }

  return entry;
}

// `setTimeout` fires immediately past this delay.
const MAX_TIMEOUT = 2 ** 31 - 1;

function _resolveReloadTimeout(fastnode: Fastnode): number | undefined {
  const value = process.env.FASTNODE_DEV_RELOAD_TIMEOUT;
  if (!value) {
    return;
  }
  const ms = Math.round(Number(value));
  if (!Number.isFinite(ms) || ms < 1) {
    fastnode.logger.warn(
      `Ignoring invalid \`FASTNODE_DEV_RELOAD_TIMEOUT\` value \`${value}\` (expected a positive number of milliseconds).`
    );
    return;
  }
  return Math.min(ms, MAX_TIMEOUT);
}
